/**
 * lib/rules.mjs —— 硬规则：他说过的、必须每次都遵守的话
 * ============================================================================
 * 🔴 2026-10-21 晚，用户抓到的问题：
 *
 *   「我刚才在另一个对话里面告诉你了改没读过的文件要先读再改，你没记住，
 *     说明功能有问题」
 *
 * 查下来的事实：
 *   那一条**记下来了** —— preferences.md 第 94 行，置信度「高」，
 *   原话都存着：「记住，每次想编辑哪个文件一定要先读取再编辑」。
 *
 *   但它**从来没有进过提示词**。
 *
 * ════════════════════════════════════════════════════════════════════════
 * 为什么会这样
 * ════════════════════════════════════════════════════════════════════════
 * 注入的做法是：
 *
 *     clipMarkdown(readPrefs(), 6000 × 0.26)   // = 1560 字
 *
 * 也就是**按文件里的顺序，取前面 1560 字**。
 *
 *   偏好总条目 141 条 → 进得去 13 条，128 条被截掉
 *   其中「用户明说 + 置信度高」76 条 → 只进去 8 条，**68 条读不到**
 *
 * 那条「先读再改」在第 94 行，位置太靠后，被截断了。
 *
 * 所以不是「没记住」，是**记住了但读不到** —— 这是设计缺口，不是模型忘性。
 *
 * ════════════════════════════════════════════════════════════════════════
 * 怎么修
 * ════════════════════════════════════════════════════════════════════════
 * 别再用「位置」决定谁进提示词，用**重要性**。
 *
 *   ① 挑出「硬规则」：用户明说 + 置信度高 + 是祈使句（该做/别做）
 *   ② 按新近度排序（他改主意了，新的赢）
 *   ③ 压成短句（去掉元信息，只留指令）
 *   ④ 单独成一段，**永远在最前面**，和偏好列表的预算分开算
 *
 * 为什么单独一段而不是塞进偏好列表：
 *   · 偏好列表是「参考资料」，按预算截断合理
 *   · 硬规则是「行为约束」，被截断就等于不存在
 *   两类东西混在一个预算里，弱势的永远被强势的挤掉。
 *
 * ⚠️ 数量要收住：硬规则也最多 N 条。全塞进去会让提示词膨胀到没人读，
 *    反而谁都不遵守。超过上限时按「新近度 × 置信度」留前 N 条。
 * ============================================================================
 */
import { parseEntries } from './habits.mjs'

/** 硬规则最多带几条（再多就不叫「硬规则」了，叫附录）。 */
export const MAX_RULES = 24

/**
 * 一条偏好算不算「硬规则」。
 *
 * 判据：
 *   ① 置信度「高」或「中」—— 「低」的不算（那是瞎猜）
 *   ② 有**原话**，或者是「用户明说」—— 两者有其一就行
 *   ③ 是祈使/约束句 —— 该做、别做、必须、不要、禁止…
 *
 * ════════════════════════════════════════════════════════════════════════
 * ⚠️ 第 ② 条的宽松是必须的，这是真实数据打回来的
 * ════════════════════════════════════════════════════════════════════════
 * 「改任何文件之前必须先读一遍再编辑」那条，原始记录是：
 *
 *   （来源：模型记录 ｜ 置信度：高 ｜ 原话：「记住，每次想编辑哪个文件一定要先读取再编辑」）
 *
 * 它的 `evidence` 字段被标成了 **「模型推断」**，于是第一版判据
 * （只看 evidence === '用户明说'）把它排除了。
 *
 * 但那条原话是**用户亲口说的**「记住，每次…」—— 打标环节把它降级了。
 *
 * 所以现在：**有原话就算强证据**。原话是逐字摘录，比「来源」这个标签可信。
 * 打标错了不该由规则引擎背锅，更不该让用户的要求被静默丢掉。
 */
/**
 * 祈使 / 约束句的判据。
 *
 * ⚠️ 2026-10-21 晚补的坑：「绝不用」不算祈使。
 *
 *   用户把「写文件绝不用 Set-Content」写进记忆后，这条**没被认成硬规则**，
 *   因为词表里只有「不许/不要/禁止」，漏了「绝不/永远/千万」这类**更强**的表达。
 *
 *   越强的否定被漏掉，越说明光靠枚举词表不够 —— 所以把强词补齐，
 *   并且后面还有第二道：**带「会…导致…失败」这种后果描述的也算**
 *   （他解释为什么不能做，说明这就是约束）。
 */
const IMPERATIVE = new RegExp([
  // 强否定（最容易漏，也最重要）
  '绝不', '绝对不', '永远不', '千万不', '坚决不', '一律不', '一概不', '不用',
  // 义务
  '必须', '一定要', '务必', '记得', '记住', '要求',
  // 禁令
  '不要', '不许', '不能', '不得', '禁止', '不准', '严禁', '勿',
  // 偏好性指令
  '最好', '应该', '需要', '别', '请',
  // 变更
  '改成', '改用', '以后',
].join('|'))

/**
 * 第二道判据：**在解释后果的句子，本身就是约束。**
 *
 *   「…绝不用 Set-Content，会写入 BOM 导致 DSH 启动失败」
 *
 * 即使没有祈使词，只要它明确说「做了 X 会导致 Y 失败」，
 * 那就等于「别做 X」—— 这是他吃过亏总结出来的，比一般偏好更该守。
 */
const CONSEQUENCE = /会(?:写入|导致|让|造成|使|引起|出现).*(?:失败|挂|崩|打不开|报错|错误|丢失|坏)/

export function isHardRule(entry) {
  const e = entry || {}
  const text = String(e.text || '')
  if (!text.trim()) return false

  // ① 置信度：低的不算
  if (!['高', '中'].includes(e.confidence)) return false

  // ② 有原话 或 标明用户明说 —— 有其一即可
  const hasQuote = Boolean(String(e.quote || '').trim())
  const saidByUser = e.evidence === '用户明说' || /用户明说/.test(String(e.raw || ''))
  if (!hasQuote && !saidByUser) return false

  /**
   * ③ 是祈使/约束句（排除「他叫枫」这种事实陈述）。
   *
   * 两条路，有其一即可：
   *   a. 有祈使词（必须/不许/绝不/以后…）
   *   b. 在解释后果（「…会导致 DSH 启动失败」）—— 那等价于「别这么做」
   */
  if (!IMPERATIVE.test(text) && !CONSEQUENCE.test(text)) return false

  return true
}

/**
 * 从 marks.md 全文里挑出硬规则，压成短句，按重要性排序。
 *
 * **纯函数**：同样的输入永远同样的输出。
 *
 * ════════════════════════════════════════════════════════════════════════
 * 排序为什么这么难写（2026-10-21 的真实教训）
 * ════════════════════════════════════════════════════════════════════════
 * 第一版只用「新近度」排序，结果：
 *   · 同一天的条目分数**完全一样**（1.191）
 *   · 于是排序退化成「文件里的行号顺序」
 *   · 「改任何文件之前必须先读一遍再编辑」排到 34/82，被截掉
 *
 * 也就是说：**只看日期等于没排序**。他最近说的话有一堆，谁重要谁不重要
 * 不能靠写入先后决定。
 *
 * 现在的排序用三个信号：
 *   ① 新近度（日期，45 天半衰期）
 *   ② 约束强度（「必须/不许/禁止」比「最好/应该」硬）
 *   ③ 操作性（能被执行的句子比"他要求加个功能"这种项目描述更该每次遵守）
 *
 * 还要去重：同一天里「他要求 A」和「他要求 AI 做 A」是同一件事，
 * 留着占位置，把真正独立的规则挤掉（前几名里就有这种重复）。
 */
export function extractRules({ prefs = '', core = '', now = Date.now(), max = MAX_RULES } = {}) {
  const fromPrefs = parseEntries(prefs).map((e) => ({ ...e, source: 'preferences' }))
  const fromCore = parseEntries(core).map((e) => ({ ...e, source: 'core' }))

  const all = [...fromPrefs, ...fromCore].filter(isHardRule)

  /**
   * 约束强度：越硬的词分越高。
   *
   * ⚠️ 2026-10-21 补：「绝不 / 绝对不 / 永远不 / 千万不」原来掉到 0.5 档。
   *    它们是**最强**的否定，却因为只认「必须/不准/禁止」而被低估，
   *    导致「写文件绝不用 Set-Content」排不进前 24 名。
   *
   *    越强的说法越被漏，越说明这里得把强词写全 ——
   *    不能只按「常见程度」排序，要按「他表达得有多硬」排序。
   */
  const strengthOf = (text) => {
    const t = String(text || '')
    // 最强：绝对性否定 / 硬性禁令
    if (/绝不|绝对不|永远不|千万不|坚决不|一律不|一概不/.test(t)) return 1.0
    if (/必须|不准|不许|禁止|绝不能|一定要|务必|严禁/.test(t)) return 1.0
    // 次强：一般禁令
    if (/不要|别|不能|不得|勿|不用/.test(t)) return 0.9
    // 记忆性 / 变更性
    if (/记住|记得|以后|改成|改用/.test(t)) return 0.8
    // 偏好性
    if (/要求|需要|应该|最好/.test(t)) return 0.6
    // 只是解释了后果（「会导致…失败」）—— 等价于禁令
    if (/会(?:写入|导致|让|造成|使|引起|出现)/.test(t)) return 0.85
    return 0.5
  }

  /**
   * 操作性：「每次做事都要遵守」的行为约束，比「某个功能该怎么做」更该常驻。
   *
   * 判据：出现「每次/任何/所有/一律/都」这类**全称量词** → 是通用约束；
   *      出现「加个/新增/实现/修改…功能」这类**一次性任务** → 是一次性要求。
   */
  const scopeOf = (text) => {
    const t = String(text || '')
    if (/每次|任何|所有|一律|总是|都要|不许盲|一律/.test(t)) return 1.0
    if (/加个|新增|添加|实现|开发|做一个|写一个|装个/.test(t)) return 0.35
    return 0.7
  }

  const scored = all.map((e) => {
    const t = Date.parse(`${e.date}T12:00:00`)
    const days = Number.isFinite(t) ? Math.max(0, (now - t) / 86_400_000) : 365
    const fresh = Math.pow(0.5, days / 45)
    const strength = strengthOf(e.text)
    const scope = scopeOf(e.text)
    return {
      ...e,
      score: fresh * (e.source === 'core' ? 1.15 : 1) * (0.4 + 0.35 * strength + 0.25 * scope),
      _fresh: fresh,
      _strength: strength,
      _scope: scope,
    }
  })

  scored.sort((a, b) => b.score - a.score || (a.date < b.date ? 1 : -1))

  /**
   * 去重：同一天里文本高度相似的只留一条（分高的）。
   *
   * ════════════════════════════════════════════════════════════════════════
   * ⚠️ 这里踩过一次很严重的误伤（2026-10-21）
   * ════════════════════════════════════════════════════════════════════════
   * 第一版把「数字、方法名、英文标识符」也一起剥了，只比中文骨架。
   * 结果：「他要求必须做第 0 件事」和「第 1 件事」剥完骨架完全一样
   *      → 60 条独立的规则被压成 5 条。
   *
   * 去重的目的是干掉「同义重复」（「他要求 X」/「他要求 AI 做 X」），
   * **不是**干掉「结构一样但内容不同」的规则。数字、标识符往往正是
   * 区分度所在（端口 8188 / 路径 C:\ComfyUI / 第 N 步）。
   *
   * 所以现在的做法：
   *   ① 只剥**纯虚词**（他要求 / AI / 的了吧呢啊）
   *   ② 保留数字、英文、标点符号区分的部分
   *   ③ 阈值提到 0.75（原来 0.6 太松）
   */
  const normalizeForDup = (s) => String(s || '')
    .replace(/他要求|要求他|他的|他的项目里|AI|晓光/g, '')
    .replace(/[，。、：；（）()「」【】]/g, '')
    .replace(/\s+/g, '')
    .trim()

  const bigrams = (s) => {
    const t = normalizeForDup(s)
    const out = new Set()
    for (let i = 0; i + 1 < t.length; i++) out.add(t.slice(i, i + 2))
    return out
  }
  const jaccard = (a, b) => {
    const A = bigrams(a)
    const B = bigrams(b)
    if (!A.size || !B.size) return 0
    let inter = 0
    for (const x of A) if (B.has(x)) inter++
    return inter / (A.size + B.size - inter)
  }

  const kept = []
  for (const e of scored) {
    // ⚠️ 阈值 0.75：同义改写能命中，「结构像但内容不同」不会
    const dup = kept.find((k) => jaccard(k.text, e.text) >= 0.75)
    if (dup) continue
    kept.push(e)
  }

  // 去掉元信息，只留「他要求什么」
  const rules = kept.slice(0, Math.max(1, max)).map((e) => ({
    id: e.id,
    text: cleanRuleText(e.text),
    date: e.date,
    section: e.section,
    source: e.source,
    quote: e.quote,
    score: Number(e.score.toFixed(3)),
  }))

  return {
    rules,
    stats: {
      candidates: all.length,
      afterDedup: kept.length,
      deduped: all.length - kept.length,
      kept: rules.length,
      dropped: Math.max(0, kept.length - rules.length),
      totalEntries: fromPrefs.length + fromCore.length,
    },
  }
}

/**
 * 把一条偏好正文压成「一句指令」。
 *
 * 原文长这样：
 *   `改任何文件之前必须先读一遍再编辑，不许盲改。（来源：模型记录 ｜ 置信度：高 ｜ 原话：「…」）`
 *
 * 压成：
 *   `改任何文件之前必须先读一遍再编辑，不许盲改`
 *
 * ⚠️ 只在**确实有括号元信息**时才切。有些条目的正文里本来就有括号
 *    （「（N=0 也写）」），切错了会丢关键信息 —— 所以切之前先确认
 *    括号里像不像元信息（含 置信度/来源/原话/明说/推断 这类词）。
 */
export function cleanRuleText(text) {
  let s = String(text || '').trim()
  // 从右往左找最后一个「（」，看它后面像不像元信息
  const at = s.lastIndexOf('（')
  if (at > 0) {
    const tail = s.slice(at)
    if (/置信度|来源|原话|用户明说|模型推断|模型记录/.test(tail)) {
      s = s.slice(0, at).trim()
    }
  }
  // 去掉句尾句号（列表里不需要）
  s = s.replace(/[。.]+$/, '')
  return s.slice(0, 80)
}

/**
 * 生成注进提示词的硬规则段。
 *
 * @param {Array} rules extractRules().rules
 * @param {object} [opts]
 * @param {number} [opts.max]
 */
export function rulesText(rules, { max = MAX_RULES } = {}) {
  const list = (rules || []).slice(0, max)
  if (!list.length) return ''
  return [
    '### 他明确要求过的（必须遵守）',
    '',
    ...list.map((r) => `- ${r.text}`),
    '',
    '这些是他**说过**的话，不是猜的。做不到就是没做到，别解释。',
  ].join('\n')
}
